function writeAudio(name, b64) {
  const bytes=Buffer.from(b64,'base64');
  const ext=bytes.subarray(0,4).toString()==='OggS'?'ogg':bytes.subarray(0,4).toString()==='RIFF'?'wav':'mp3';
  let filename=name+'.'+ext;
  if(ext==='ogg'){
    const hash=createHash('sha256').update(bytes).digest('hex');
    const mp3=path.join(audio,name+'.mp3');
    if(audioHashes[name]!==hash||!fs.existsSync(mp3)){
      const original=path.join(audio,filename);fs.writeFileSync(original,bytes);
      const result=spawnSync('ffmpeg',['-y','-loglevel','error','-i',original,'-codec:a','libmp3lame','-b:a','96k','-ar','44100','-ac','2',mp3],{encoding:'utf8'});
      if(result.error||result.status!==0)throw Error('Audio conversion requires ffmpeg: '+(result.error?.message||result.stderr));
      audioHashes[name]=hash;
    }
    const original=path.join(audio,filename);if(fs.existsSync(original))fs.unlinkSync(original);
    filename=name+'.mp3';
  }else fs.writeFileSync(path.join(audio,filename),bytes);
  return 'assets/audio/'+filename;
}
